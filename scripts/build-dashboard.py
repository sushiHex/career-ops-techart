# --- comp extraction ---------------------------------------------------------
# Reports were authored across many batches with drifting heading conventions, so a
# single "## Comp" match only catches ~half. Comp actually lives in one of:
#   1. a "## Comp" section          (early reports)
#   2. comp_posted: "..."           (Machine Summary YAML -- machine-authored, cleanest)
#   3. a "## ...Comp..." heading    ("Culture vs Comp", "Block D -- Compensation", "D) Comp & Demand")
# We try them in that order and normalize every hit to a compact "$174K-$253K" band.
# A guarded prose fallback (3) only trusts a range on a synthesis line so it never
# grabs the candidate's own target/floor figures (e.g. "target $X-YK, floor $ZK")
# as the role's pay.
_MONEY = r'\$?\s*[\d,.]+\s*[KkMm]?'
RANGE_RE = re.compile(r'\$\s*[\d,.]+\s*[KkMm]?\s*(?:-|–|—|to)\s*' + _MONEY)
# A $ range is the candidate's own number (target/floor/past comp), not the role's pay,
# when the text JUST BEFORE it says so. Checked on the ~35 chars preceding each range -- NOT the
# whole line -- so a downstream "AIP (~10-15% target)" bonus-target % never disqualifies a
# real posted band like "Verbatim: CA $211,800-$306,625 ... (~10-15% target)".
# The window is also clamped to the START OF THE LINE, because a blind 35-char lookback
# reaches back across the line break into the PREVIOUS sentence. That silently blanked
# one real posted band: the line is just "**Comp:** $310-520K", but the sentence above
# it ended "...isn't their kind of TA.", and that stray "their"
# disqualified the band (found 2026-07-30). Only text on the same line can qualify it.
#
# The candidate's first name and past employers join the cue list, since report prose
# introduces their own figures that way ("at Studio X she earned..."). Both come from
# config/profile.yml; an unconfigured clone simply has fewer cues.
_OWN_CUES = [r'target', r'floor', r'\bvs\b', r'\b(?:his|her|their|my)\b', r'step-?down',
             r'current', r'prior'] + \
            [r'\b%s\b' % re.escape(w) for w in
             [CANDIDATE['first_name']] + CANDIDATE['past_employers'] if w]
_OWN_PRE = re.compile('|'.join(_OWN_CUES), re.I)
# cue that a line states the evaluator's own total estimate (preferred over a raw market ref)
_SYNTH = re.compile(r'estimate|total comp|realistic|typical|lands? in|likely', re.I)

def _norm_k(tok):
    """'$174,000' / '$174K' / '$1.2M' -> '$174K' / '$1200K'. None if unparseable."""
    m = re.match(r'\$?\s*([\d,.]+)\s*([KkMm]?)', tok.strip())
    if not m:
        return None
    try:
        val = float(m.group(1).replace(',', ''))
    except ValueError:
        return None
    suf = m.group(2).lower()
    if suf == 'm':
        val *= 1000.0
    elif suf != 'k' and val >= 1000:   # bare full-dollar figure -> thousands
        val /= 1000.0
    return '$%dK' % round(val)

def _clean_ranges(text):
    """All well-formed $ ranges in text whose immediate preceding context is NOT about
    the candidate's own target/floor/past comp, normalized to '$LoK-$HiK', in document
    order."""
    out = []
    for m in RANGE_RE.finditer(text):
        line_start = text.rfind('\n', 0, m.start()) + 1
        if _OWN_PRE.search(text[max(line_start, m.start() - 35):m.start()]):
            continue
        parts = re.findall(_MONEY, m.group(0))
        if len(parts) >= 2:
            lo, hi = _norm_k(parts[0]), _norm_k(parts[-1])
            if lo and hi:
                out.append('%s-%s' % (lo, hi))
    return out

def _first_clean(text):
    r = _clean_ranges(text)
    if r:
        return r[0]
    return _single_ended(text)

# Some postings state one bound, not a range ("base up to $269,000", "$200K+"). RANGE_RE
# needs two figures, so those rendered BLANK -- which reads as "no comp data" when the
# number is right there. Show the bound with its direction rather than inventing a range.
_UP_TO = re.compile(r'\b(?:up to|max(?:imum)?(?: of)?|no more than)\s*(\$\s*[\d,.]+\s*[KkMm]?)', re.I)
_FROM = re.compile(r'\b(?:from|starting at|at least|min(?:imum)?(?: of)?)\s*(\$\s*[\d,.]+\s*[KkMm]?)', re.I)
_PLUS = re.compile(r'(\$\s*[\d,.]+\s*[KkMm]?)\s*\+')

def _single_ended(text):
    for line in text.splitlines():
        line_start = 0
        for rx, fmt in ((_UP_TO, '≤%s'), (_FROM, '%s+'), (_PLUS, '%s+')):
            m = rx.search(line)
            if not m:
                continue
            if _OWN_PRE.search(line[max(line_start, m.start() - 35):m.start()]):
                continue
            v = _norm_k(m.group(1))
            if v:
                return fmt % v
    return ''

# Some employers state TWO bands for ONE req in a single sentence, in the shape "the base
# salary range is $AK-$BK for Level 3, and $CK-$DK for Level 4." Taking only the first
# range reports the LOWER ladder and understates the role. When ONE LINE carries level
# markers and 2+ clean ranges, span them.
# Match ONLY the posting's own construction: a range IMMEDIATELY FOLLOWED by "for Level N".
# A looser "line mentions a level" test over-spans: it merged an unrelated comparator
# sentence, one that names a lower level's band while discussing a different req, into a
# fake spanned band for a posting that never stated one, and it likewise merged a posted
# band with a separate ESTIMATE figure that happened to share the line. Requiring the
# level marker to TRAIL the range excludes both, because in a comparator the level word
# leads instead.
_BAND_FOR_LEVEL = re.compile(
    r'(\$\s*[\d,.]+\s*[KkMm]?\s*(?:-|–|—|to)\s*\$?\s*[\d,.]+\s*[KkMm]?)'   # the range
    r'(?:\s*USD)?[\s*]{0,4}[(\[]?\s*(?:for\s+)?(?:level\s*\d|L[3-7])\b', re.I)

def _span_if_leveled(text):
    for line in text.splitlines():
        bands = [m.group(1) for m in _BAND_FOR_LEVEL.finditer(line)]
        if len(bands) < 2:
            continue
        lows, highs = [], []
        for b in bands:
            parts = re.findall(_MONEY, b)
            if len(parts) < 2:
                return ''
            lo, hi = _norm_k(parts[0]), _norm_k(parts[-1])
            if not lo or not hi:
                return ''
            lows.append(int(re.sub(r'[^\d]', '', lo)))
            highs.append(int(re.sub(r'[^\d]', '', hi)))
        return '$%dK-$%dK' % (min(lows), max(highs))
    return ''

def extract_comp(txt):
    # 0. a single line stating multiple LEVEL bands is the posted band and the most
    #    specific signal in the document -- span it before anything else.
    spanned = _span_if_leveled(txt)
    if spanned:
        return spanned
    # 1. explicit "## Comp" section (early reports)
    cs = re.search(r'## Comp\s*\n(.+?)(?:\n##|\Z)', txt, re.S)
    if cs:
        r = _first_clean(cs.group(1))
        if r:
            return r
    # 2. comp_posted from Machine Summary YAML -- machine-authored posted band, cleanest.
    #    If the value is explicitly flagged a market ESTIMATE (indie studios that publish
    #    no band), render it distinctly as "~$X-$Y est" so it's never mistaken for a posted
    #    band. Trigger only on the literal word "estimate" (no real posted band uses it).
    mp = re.search(r'comp_posted:\s*["\']?(.+)', txt)
    if mp:
        r = _first_clean(mp.group(1))
        if r:
            return '~%s est' % r if re.search(r'estimate', mp.group(1), re.I) else r
    # 3. any "## ...Comp..." heading section ("Culture vs Comp", "Block C -- Comp",
    #    "D) Comp & Demand"). Prefer a range on the evaluator's synthesis line; else the
    #    first clean range (usually the verbatim posted band).
    sections = []
    for hm in re.finditer(r'^##+\s*.*comp.*$', txt, re.I | re.M):
        start = hm.end()
        end = re.search(r'\n##', txt[start:])
        sections.append(txt[start:start + (end.start() if end else len(txt))])
    for sec in sections:
        for line in sec.splitlines():
            if _SYNTH.search(line):
                r = _first_clean(line)
                if r:
                    return r
    for sec in sections:
        r = _first_clean(sec)
        if r:
            return r
    # 4. floor-only fallback: union / CBA roles publish an HOURLY minimum ("no less than
    #    $62.74 an hour") instead of a salaried band. Annualize (x2080) and render as a
    #    floor "$131K+" so the row isn't blank. Lowest priority -- only when no real range
    #    exists anywhere, so it never overrides a posted band.
    hm = re.search(r'\$\s*(\d{1,3}(?:\.\d{1,2})?)\s*(?:/\s*hr|/\s*hour|\s*(?:an|per)\s+hour)', txt, re.I)
    if hm:
        try:
            annual = float(hm.group(1)) * 2080
            return '$%dK+' % round(annual / 1000)
        except ValueError:
            pass
    return ''

