# The tier a row lands in when its location is inside the commute area. The area and its
# label come from config/location.json (see presets/locations/).
COMMUTE = 'Commute'
_ONSITE = ['(onsite)', 'onsite', 'on-site', 'on site', 'in-person', 'in person', '5-day', '5 day', 'hybrid']

def tier(co, role, loc, note):
    """Derive the location tier from LOCATION TEXT only. A company name is never evidence:
    one employer can post an LA-onsite role and a remote one in the same week, so a name
    must never override an explicit listing. Rows the text cannot place read 'Check'."""
    t = (loc + ' ' + note).lower()

    # 1. Explicit eval-assigned **[tag]** wins (most authoritative human signal)
    m = re.search(r'\*\*\[([^\]]+)\]\*\*', loc + ' ' + note)
    if m:
        tag = m.group(1).lower()
        if ('onsite' in tag or 'hybrid' in tag or 'commute' in tag
                or LOCATION.commute_label.lower() in tag): return COMMUTE
        if 'negoti' in tag or 'gated' in tag or 'confirm' in tag: return 'Negotiation-gated'
        if 'remote' in tag: return 'Remote-US'

    onsite = any(w in t for w in _ONSITE)
    # The commute area is read from the LOCATION only, never the note prose: a note
    # saying "no SoCal office" is about the commute area without being in it.
    socal = LOCATION.in_commute_area(loc)
    remote_ok = ('remote' in t) and not any(neg in t for neg in ['not remote', 'no remote', "isn't remote", 'not fully remote'])

    # 2. Location text decides. Explicit onsite language forces a commute classification even
    #    for a company that CAN be remote (the Netflix-LA-onsite bug); a remote offer with an
    #    optional/preferred SoCal office is still Remote-US.
    if onsite:
        if socal: return COMMUTE
        if remote_ok: return 'Remote-US'   # onsite outside the commute OR remote (e.g. "onsite NYC or remote")
        return 'Check'
    if remote_ok: return 'Remote-US'
    if socal: return COMMUTE

    # 3. Negotiation signals
    if ('confirm ca-remote' in t or 'confirm remote' in t or 'location-gated' in t
            or 'negotiat' in t): return 'Negotiation-gated'
    return 'Check'

# The candidate's own bio recurs in nearly EVERY packet regardless of target company, so
# generic job-level and function words are useless discriminators: a word from the
# candidate's own specialty can appear in most packet files. Prefer words that are
# actually RARE across the corpus.
GENERIC_ROLE_WORDS = {
    'senior', 'staff', 'principal', 'lead', 'software', 'engineer', 'engineering',
    'technical', 'technology', 'manager', 'director', 'specialist', 'artist',
    'scientist', 'architect', 'applied', 'developer', 'systems', 'platform',
}

def _role_keywords(role):
    """Return (rl, require_match): the word-list used to judge whether a document is
    substantively ABOUT this role, preferring rare/corpus-distinctive words over generic
    job-level ones. Shared by prepped_file() (pick the packet) and find_cv() (pick the
    right CV mention inside a multi-role packet via proximity to these same words)."""
    all_words = [w for w in re.findall(r'[a-z]+', role.lower()) if len(w) > 4]
    specific = [w for w in all_words if w not in GENERIC_ROLE_WORDS]
    rare = [w for w in specific if role_word_docfreq.get(w, 0) <= 0.4 * max(len(kitfiles), 1)]
    rl = rare or specific or all_words  # degrade gracefully if the role has no rare/specific word
    require_match = bool(rare or specific)  # only demand a hit when we have a real signal to check
    # When NO rare word exists, every remaining keyword is corpus-common -- i.e. it is the
    # candidate's own bio, not this role. A title that reduces to one word from the
    # candidate's own history matches most packets for that reason alone. Falling back to
    # those words silently defeats the docfreq filter and lets a bio echo count as a role
    # match. Callers use has_rare to demand stronger corroboration.
    has_rare = bool(rare)
    return rl, require_match, has_rare

def prepped_file(co, role):
    """Return the packet/prep filename that best matches this role, or None.
    A file must substantively mention BOTH the company (>=2x AND not dwarfed by
    some OTHER tracked company's mention count in the same file -- e.g. a past employer
    said 8x as background bio inside a packet where the target appears 44x should NOT
    count as a packet for the past employer) and the role. The role match prefers RARE,
    corpus-distinctive keywords (e.g. "omniverse", "firefly") over generic
    job-level words that appear in nearly every packet via the candidate's recurring bio
    (e.g. "engineer", "rigging") -- see GENERIC_ROLE_WORDS + role_word_docfreq.
    Role-match strength is measured as DENSITY (hits per 1000 words), not a raw
    count -- otherwise a giant multi-company batch file always "wins" on volume
    alone against a short, focused, dedicated packet just because it's longer.
    Among qualifying files, prefer the most RECENT (by filename date) -- this
    project's convention is that later files (v2, "session", "packet") supersede
    earlier drafts, not that the highest raw mention-count wins."""
    cl = co.lower().split()[0]
    rl, require_match, has_rare = _role_keywords(role)
    candidates = []
    for fn, txt in kitfiles.items():
        co_count = txt.count(cl)
        if co_count < 2:
            continue
        # A company from the candidate's OWN WORK HISTORY appears as background bio in
        # nearly every packet, so a raw share threshold is not enough: a past employer hit
        # ~30% of the target inside one apply-session packet and mis-attached that packet to
        # an unrelated req at the past employer (found 2026-08-03). A file is only ABOUT a company if
        # either the FILENAME names it (the convention here: acme-*, globex-*) or
        # the company is a dominant subject of a genuinely multi-company file, not a 30% echo.
        named_in_filename = cl in fn.lower()
        if not named_in_filename and co_count < max(2, 0.6 * file_max_co_count.get(fn, 0)):
            continue  # incidental / bio mention -> not a packet for this company
        # No rare role word means the only thing we can match on is bio vocabulary. That is
        # not evidence a general prep session covers THIS req, so require the filename to
        # name the company before attributing. A dedicated acme-* packet is still
        # safe to attribute on a weak role word; a 15k-word multi-company batch file is not.
        if not has_rare and not named_in_filename:
            continue
        role_count = sum(txt.count(w) for w in rl) if rl else 0
        if require_match and role_count == 0:
            continue
        density = role_count / kit_wordcount.get(fn, 1) * 1000
        dm = re.search(r'(\d{4}-\d{2}-\d{2})', fn)
        vm = re.search(r'-v(\d+)-', fn)  # explicit revision marker: "...-v2-<date>.md" supersedes "...-<date>.md"
        candidates.append((int(vm.group(1)) if vm else 1, round(density, 3), dm.group(1) if dm else '', co_count, fn))
    if not candidates:
        return None
    # version FIRST (an explicit "-v2-" always supersedes "-v1-" of the same doc, even if
    # the revision has fewer incidental keyword hits); THEN role-match density (this is
    # what actually distinguishes two unrelated documents that both mention the company --
    # a short dedicated packet mentioning the role 18x in 700 words is a much stronger
    # match than a 300-hit mention buried in an 18,000-word multi-company batch file);
    # date/company-count are only a final tiebreak.
    candidates.sort(reverse=True)
    return candidates[0][4]

# A packet's opening "Resume:" note is often CONDITIONAL guidance covering every role in
# the file, e.g. "Resume: Jane-Smith-TA-CV.pdf (craft roles); AI-led CV variant better
# for AI/FDE/enablement ones." Proximity cannot parse that, so it handed the craft half to
# 8 roles including a Netflix agent-platform req (found 2026-07-30). Such a line names no
# single role's CV, so it must not count as an explicit mention -- better to fall through to
# the lane guess, which the caller labels as unconfirmed, than to assert a wrong CV.
_CV_HEDGE = re.compile(
    r'craft roles|better for|variant|instead|unless|override|general|'
    r'\bfor (?:ai|craft|the ai|these)\b|\bor\b.*\bcv\b|all (?:of them|five|4|5)', re.I)

def _is_conditional_cv_line(text, match):
    ls = text.rfind('\n', 0, match.start()) + 1
    le = text.find('\n', match.end())
    line = text[ls:le if le != -1 else len(text)]
    return len(CV_PATTERN.findall(line)) > 1 or bool(_CV_HEDGE.search(line))

def find_cv(role, report_txt, packet_fn):
    """Return (cv_filename, confirmed: bool). Looks for an EXPLICIT "<Name>-*-CV"
    mention -- never a guess when one exists on record:
      1. The per-role report (unambiguous -- one report, one role) always wins if it
         names a CV.
      2. Otherwise scan the matched packet file. Packets often cover MULTIPLE roles
         (batch/kit/session docs), so a global "first CV mentioned" search can grab the
         wrong one -- instead pick whichever CV mention sits CLOSEST to an occurrence of
         this role's own distinctive keyword (same rl word-list prepped_file() used to
         pick the packet in the first place).
    Returns (None, False) if no explicit mention exists anywhere -- caller should fall
    back to the coarse lane-based guess and say so, not present it as fact."""
    for txt in (report_txt or '',):
        if txt:
            m = CV_PATTERN.search(txt)
            if m:
                cv = CV_CANON.get(_norm_cv(m.group(0)))
                if cv:
                    return cv, True
    if not packet_fn or packet_fn not in kitfiles:
        return None, False
    ptxt = kitfiles[packet_fn]  # already lowercased
    cv_matches = [m for m in CV_PATTERN.finditer(ptxt) if not _is_conditional_cv_line(ptxt, m)]
    if not cv_matches:
        return None, False
    if len(cv_matches) == 1:
        cv = CV_CANON.get(_norm_cv(cv_matches[0].group(0)))
        return (cv, True) if cv else (None, False)
    rl, _, _ = _role_keywords(role)
    kw_positions = [m.start() for w in rl for m in re.finditer(re.escape(w), ptxt)]
    if not kw_positions:
        # can't disambiguate which of several CV mentions is "ours" -> don't guess
        return None, False
    best_cv, best_dist = None, None
    for m in cv_matches:
        dist = min(abs(m.start() - p) for p in kw_positions)
        if best_dist is None or dist < best_dist:
            cv = CV_CANON.get(_norm_cv(m.group(0)))
            if cv:
                best_cv, best_dist = cv, dist
    return (best_cv, True) if best_cv else (None, False)

